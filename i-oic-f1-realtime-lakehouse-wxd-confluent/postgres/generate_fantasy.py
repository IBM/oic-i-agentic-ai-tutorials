"""Generate postgres/fantasy_league.sql: a fictional fantasy-league app database.

The fantasy app is a separate operational system (it lives in PostgreSQL, not the
lakehouse). Presto joins it to the lakehouse at query time, so nothing is copied.

    python postgres/generate_fantasy.py   # rewrites fantasy_league.sql (deterministic)
"""

import random
from pathlib import Path

# 2026 grid with a pre-season price in $M. Prices reflect pre-season expectations, not results.
PRICES = {
    "max_verstappen": 30.0, "norris": 29.5, "piastri": 27.0, "leclerc": 26.0, "hamilton": 25.0,
    "russell": 24.0, "antonelli": 19.0, "alonso": 14.0, "hadjar": 13.5, "sainz": 13.0,
    "albon": 11.0, "gasly": 11.0, "lawson": 10.0, "stroll": 9.5, "bearman": 9.5, "ocon": 9.0,
    "hulkenberg": 9.0, "bortoleto": 8.5, "colapinto": 8.0, "lindblad": 7.5, "perez": 8.0, "bottas": 7.5,
}
BUDGET = 100.0
TEAM_WORDS_A = ["Pit Lane", "Apex", "Slipstream", "DRS", "Chicane", "Pole", "Box Box", "Undercut",
                "Parc Fermé", "Grid", "Late Braking", "Dirty Air", "Purple Sector", "Safety Car"]
TEAM_WORDS_B = ["Prophets", "Hunters", "Rockets", "Collective", "Syndicate", "Racing", "Dreamers",
                "Engineers", "Strategists", "Club", "United", "Express", "Legends", "Crew"]
FIRST = ["Asha", "Ben", "Chen", "Dara", "Elif", "Femi", "Gita", "Hugo", "Ines", "Jonas", "Kai", "Lena",
         "Mateo", "Nia", "Omar", "Priya", "Quinn", "Rosa", "Sami", "Tara", "Uma", "Victor", "Wren", "Yuki",
         "Zane", "Amara", "Bruno", "Clara", "Dev", "Ella", "Farid", "Greta", "Hana", "Ivan", "Jade", "Kofi",
         "Lucia", "Milan", "Noor", "Oscar"]
COUNTRIES = ["India", "United Kingdom", "Brazil", "Japan", "Italy", "Netherlands", "Australia",
             "United States", "Germany", "Spain", "Mexico", "Canada"]


def pick_team(rng: random.Random) -> list[str]:
    drivers = list(PRICES)
    while True:
        team = rng.sample(drivers, 5)
        if sum(PRICES[d] for d in team) <= BUDGET:
            return team


def main() -> None:
    rng = random.Random(2026)
    out = ["-- Fantasy-league app database (fictional data). Generated by generate_fantasy.py.",
           "DROP TABLE IF EXISTS fantasy_picks;",
           "DROP TABLE IF EXISTS fantasy_managers;",
           "DROP TABLE IF EXISTS driver_prices;",
           "",
           "CREATE TABLE fantasy_managers (\n  manager_id INT PRIMARY KEY,\n  manager_name VARCHAR(60) NOT NULL,\n"
           "  team_name VARCHAR(80) NOT NULL,\n  country VARCHAR(40),\n  joined_on DATE\n);",
           "CREATE TABLE driver_prices (\n  season INT NOT NULL,\n  driver_id VARCHAR(40) NOT NULL,\n"
           "  price_musd NUMERIC(5,1) NOT NULL,\n  PRIMARY KEY (season, driver_id)\n);",
           "CREATE TABLE fantasy_picks (\n  manager_id INT REFERENCES fantasy_managers(manager_id),\n"
           "  season INT NOT NULL,\n  driver_id VARCHAR(40) NOT NULL,\n  is_captain BOOLEAN NOT NULL DEFAULT FALSE,\n"
           "  PRIMARY KEY (manager_id, season, driver_id)\n);",
           ""]
    out.append("INSERT INTO driver_prices (season, driver_id, price_musd) VALUES")
    out.append(",\n".join(f"  (2026, '{d}', {p})" for d, p in PRICES.items()) + ";")
    out.append("")

    managers, picks, used = [], [], set()
    for i, first in enumerate(FIRST, start=1):
        while True:
            name = f"{rng.choice(TEAM_WORDS_A)} {rng.choice(TEAM_WORDS_B)}"
            if name not in used:
                used.add(name)
                break
        joined = f"2026-0{rng.randint(1, 2)}-{rng.randint(10, 28)}"
        managers.append(f"  ({i}, '{first} {chr(65 + rng.randint(0, 25))}.', '{name}', '{rng.choice(COUNTRIES)}', '{joined}')")
        team = pick_team(rng)
        captain = rng.choice(team)
        picks += [f"  ({i}, 2026, '{d}', {'TRUE' if d == captain else 'FALSE'})" for d in team]

    out.append("INSERT INTO fantasy_managers (manager_id, manager_name, team_name, country, joined_on) VALUES")
    out.append(",\n".join(managers) + ";")
    out.append("")
    out.append("INSERT INTO fantasy_picks (manager_id, season, driver_id, is_captain) VALUES")
    out.append(",\n".join(picks) + ";")
    Path(__file__).with_name("fantasy_league.sql").write_text("\n".join(out) + "\n")
    print(f"Wrote {len(managers)} managers and {len(picks)} picks")


if __name__ == "__main__":
    main()
